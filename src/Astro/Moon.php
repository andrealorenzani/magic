<?php
declare(strict_types=1);

namespace Magic\Astro;

final class Moon
{
    /** Longitude terms. */
    private const TERMS = [
        [0, 0, 1, 0, 6288774], [2, 0, -1, 0, 1274027], [2, 0, 0, 0, 658314],
        [0, 0, 2, 0, 213618], [0, 1, 0, 0, -185116], [0, 0, 0, 2, -114332],
        [2, 0, -2, 0, 58793], [2, -1, -1, 0, 57066], [2, 0, 1, 0, 53322],
        [2, -1, 0, 0, 45758], [0, 1, -1, 0, -40923], [1, 0, 0, 0, -34720],
        [0, 1, 1, 0, -30383], [2, 0, 0, -2, 15327], [0, 0, 1, 2, -12528],
        [0, 0, 1, -2, 10980], [4, 0, -1, 0, 10675], [0, 0, 3, 0, 10034],
        [4, 0, -2, 0, 8548], [2, 1, -1, 0, -7888], [2, 1, 0, 0, -6766],
        [1, 0, -1, 0, -5163], [1, 1, 0, 0, 4987], [2, -1, 1, 0, 4036],
        [2, 0, 2, 0, 3994], [4, 0, 0, 0, 3861], [2, 0, -3, 0, 3665],
        [0, 1, -2, 0, -2689], [2, 0, -1, 2, -2602], [2, -1, -2, 0, 2390],
        [1, 0, 1, 0, -2348], [2, -2, 0, 0, 2236], [0, 1, 2, 0, -2120],
        [0, 2, 0, 0, -2069], [2, -2, -1, 0, 2048], [2, 0, 1, -2, -1773],
        [2, 0, 0, 2, -1595], [4, -1, -1, 0, 1215], [0, 0, 2, 2, -1110],
    ];

    /** Apparent geocentric ecliptic longitude in degrees (accuracy ≈ 0.01°). */
    public static function longitude(float $jd): float
    {
        $T = Angles::centuries($jd);
        $Lp = 218.3164477 + 481267.88123421 * $T;
        $Fdeg = 93.272095 + 483202.0175233 * $T;
        $D = Angles::rad(297.8501921 + 445267.1114034 * $T);
        $M = Angles::rad(357.5291092 + 35999.0502909 * $T);
        $Mp = Angles::rad(134.9633964 + 477198.8675055 * $T);
        $F = Angles::rad($Fdeg);
        $E = 1 - 0.002516 * $T - 0.0000074 * $T * $T;

        $sum = 0.0;
        foreach (self::TERMS as [$d, $m, $mp, $f, $c]) {
            $e = abs($m) === 2 ? $E * $E : (abs($m) === 1 ? $E : 1.0);
            $sum += $c * $e * sin($d * $D + $m * $M + $mp * $Mp + $f * $F);
        }
        $sum += 3958 * sin(Angles::rad(119.75 + 131.849 * $T))
            + 1962 * sin(Angles::rad($Lp - $Fdeg))
            + 318 * sin(Angles::rad(53.09 + 479264.29 * $T));

        return Angles::norm360($Lp + $sum / 1e6 + Angles::nutationLongitude($T));
    }
}
